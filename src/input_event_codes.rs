/// Synchronization events.
#[derive(Debug, PartialEq, Clone, Copy)]
pub enum Syn {
  SynReport,
  SynConfig,
  SynMtReport,
  SynDropped,
  SynMax,
  SynCnt,
}

impl Syn {
  /// The raw numeric event code, as defined by the Linux kernel.
  pub fn code(&self) -> u32 {
    match self {
      Syn::SynReport => 0,
      Syn::SynConfig => 1,
      Syn::SynMtReport => 2,
      Syn::SynDropped => 3,
      Syn::SynMax => 0xf,
      Syn::SynCnt => Syn::SynMax.code() + 1,
    }
  }

  /// The literal name of the constant as it appears in the Linux kernel header.
  pub fn name(&self) -> &'static str {
    match self {
      Syn::SynReport => "SYN_REPORT",
      Syn::SynConfig => "SYN_CONFIG",
      Syn::SynMtReport => "SYN_MT_REPORT",
      Syn::SynDropped => "SYN_DROPPED",
      Syn::SynMax => "SYN_MAX",
      Syn::SynCnt => "SYN_CNT",
    }
  }
}

