//! (Mostly) Literal translation of [input-event-codes.h](https://github.com/torvalds/linux/blob/master/include/uapi/linux/input-event-codes.h).

/// Device properties and quirks
#[derive(Debug, PartialEq, Clone, Copy)]
pub enum InputProp {
  /// needs a pointer
  InputPropPointer,
  /// direct input devices
  InputPropDirect,
  /// has button(s) under pad
  InputPropButtonpad,
  /// touch rectangle only
  InputPropSemiMt,
  /// softbuttons at top of pad
  InputPropTopbuttonpad,
  /// is a pointing stick
  InputPropPointingStick,
  /// has accelerometer
  InputPropAccelerometer,
  /// pressure triggers clicks
  InputPropPressurepad,

  InputPropMax,
  InputPropCnt,
}

impl InputProp {
  /// The raw numeric event code, as defined by the Linux kernel.
  pub fn code(&self) -> u32 {
    match self {
      InputProp::InputPropPointer => 0x00,
      InputProp::InputPropDirect => 0x01,
      InputProp::InputPropButtonpad => 0x02,
      InputProp::InputPropSemiMt => 0x03,
      InputProp::InputPropTopbuttonpad => 0x04,
      InputProp::InputPropPointingStick => 0x05,
      InputProp::InputPropAccelerometer => 0x06,
      InputProp::InputPropPressurepad => 0x07,
      InputProp::InputPropMax => 0x1f,
      InputProp::InputPropCnt => InputProp::InputPropMax.code() + 1,
    }
  }

  /// The literal name of the constant as it appears in the Linux kernel header.
  pub fn name(&self) -> &'static str {
    match self {
      InputProp::InputPropPointer => "INPUT_PROP_POINTER",
      InputProp::InputPropDirect => "INPUT_PROP_DIRECT",
      InputProp::InputPropButtonpad => "INPUT_PROP_BUTTONPAD",
      InputProp::InputPropSemiMt => "INPUT_PROP_SEMI_MT",
      InputProp::InputPropTopbuttonpad => "INPUT_PROP_TOPBUTTONPAD",
      InputProp::InputPropPointingStick => "INPUT_PROP_POINTING_STICK",
      InputProp::InputPropAccelerometer => "INPUT_PROP_ACCELEROMETER",
      InputProp::InputPropPressurepad => "INPUT_PROP_PRESSUREPAD",
      InputProp::InputPropMax => "INPUT_PROP_MAX",
      InputProp::InputPropCnt => "INPUT_PROP_CNT",
    }
  }
}

